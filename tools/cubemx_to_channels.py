@dataclass
class ADCConfig:
    instance: str                      # e.g. "ADC1"
    init: list[tuple[str, str]]        # [(field, value), ...]
    multimode: list[tuple[str, str]] | None
    inputs: list[dict[str, str]]       # list of sConfig field dicts


def parse_mx_adc_init(body: str, hadc_var: str) -> ADCConfig | None:
    """Parse one `MX_ADC*_Init` body. `hadc_var` is the local handle name
    CubeMX uses, e.g. `hadc1` for ADC1."""
    instance_match = re.search(
        rf'\b{re.escape(hadc_var)}\.Instance\s*=\s*(ADC\d+)\s*;', body)
    if not instance_match:
        return None
    instance = instance_match.group(1)

    # hadcN.Init.X = Y;  -- preserve declaration order
    init_pairs: list[tuple[str, str]] = []
    for m in re.finditer(
            rf'\b{re.escape(hadc_var)}\.Init\.(\w+)\s*=\s*([^;]+);', body):
        init_pairs.append((m.group(1), m.group(2).strip()))

    # multimode: only present when MultiModeConfigChannel is called.
    multimode: list[tuple[str, str]] | None = None
    if re.search(r'\bHAL_ADCEx_MultiModeConfigChannel\s*\(', body):
        multimode = []
        for m in re.finditer(r'\bmultimode\.(\w+)\s*=\s*([^;]+);', body):
            multimode.append((m.group(1), m.group(2).strip()))

    # Each HAL_ADC_ConfigChannel call corresponds to one input. CubeMX sets
    # the common sConfig fields (SamplingTime, SingleDiff, ...) once and then
    # mutates only Channel/Rank before each subsequent call, relying on the
    # struct persisting its other fields. Our per-input storage is independent,
    # so snapshot the running sConfig at each call to give every input its full
    # field set (same walk the TIM/injected parsers use).
    inputs: list[dict[str, str]] = []
    running: dict[str, str] = {}
    token = re.compile(
        r'\bsConfig\.(\w+)\s*=\s*([^;]+);'
        r'|\bHAL_ADC_ConfigChannel\s*\(')
    for m in token.finditer(body):
        if m.group(1) is not None:
            running[m.group(1)] = m.group(2).strip()
        else:
            inputs.append(dict(running))

    return ADCConfig(
        instance=instance, init=init_pairs,
        multimode=multimode, inputs=inputs,
    )


def channel_index_from_constant(channel: str) -> int | None:
    """`ADC_CHANNEL_6` -> 6. Returns None for non-numeric channels
    (e.g. ADC_CHANNEL_TEMPSENSOR), which the sparse `inputs[N]` array
    can't index by physical IN# anyway."""
    m = re.match(r'ADC_CHANNEL_(\d+)\b', channel)
    return int(m.group(1)) if m else None


def gen_adc_macros(adcs: list[ADCConfig]) -> str:
    parts: list[str] = []
    for adc in adcs:
        name = adc.instance
        parts.append(f"// ----- {name} -----")
        parts.append("")

        # Instance constant.
        parts.append(f"#define HW_ADC_CUBEMX_HADC_INSTANCE_{name}  {name}")
        parts.append("")

        # hadc.Init fields.
        if adc.init:
            init_lines = aligned_assignments(adc.init, indent="    ")
            parts.append(emit_macro(f"HW_ADC_CUBEMX_HADC_INIT_{name}",
                                    init_lines))
            parts.append("")

        # multimode (if present).
        if adc.multimode is not None and adc.multimode:
            mm_lines = aligned_assignments(adc.multimode, indent="    ")
            parts.append(emit_macro(f"HW_ADC_CUBEMX_MULTIMODE_{name}",
                                    mm_lines))
            parts.append("")

        # Regular-sequence inputs.
        if adc.inputs:
            input_lines: list[str] = []
            for inp in adc.inputs:
                ch = inp.get("Channel", "")
                idx = channel_index_from_constant(ch)
                if idx is None:
                    print(f"  WARN: skipping non-numeric channel {ch!r} "
                          f"on {name} (internal channels not yet "
                          f"supported)", file=sys.stderr)
                    continue
                # Sub-struct field assignments, aligned.
                sc_pairs = list(inp.items())
                sc_lines = aligned_assignments(sc_pairs,
                                               indent="            ")
                input_lines.append(f"    [{idx}] =")
                input_lines.append("    {")
                input_lines.append("        .enabled = true,")
                input_lines.append("        .sConfig =")
                input_lines.append("        {")
                input_lines.extend(sc_lines)
                input_lines.append("        },")
                input_lines.append("    },")
            parts.append(emit_macro(f"HW_ADC_CUBEMX_INPUTS_{name}",
                                    input_lines))
            parts.append("")

            # sim mirror: same enabled-input set, just with a name string.
            sim_lines: list[str] = []
            for inp in adc.inputs:
                ch = inp.get("Channel", "")
                idx = channel_index_from_constant(ch)
                if idx is None:
                    continue
                sim_lines.append(
                    f'    [{idx}] = {{ .enabled = true, '
                    f'.inputNameStr = "{name}_IN{idx}" }},'
                )
            parts.append(emit_macro(f"HW_ADC_CUBEMX_SIM_INPUTS_{name}",
                                    sim_lines))
            parts.append("")

    return "\n".join(parts).rstrip() + "\n"


def write_adc_header(adcs: list[ADCConfig]) -> None:
    macros = gen_adc_macros(adcs)
    content = (
        f"{file_header('cubemx_to_channels.py')}"
        f"\n"
        f"#ifndef HW_ADC_CHANNELS_CUBEMX_H\n"
        f"#define HW_ADC_CHANNELS_CUBEMX_H\n"
        f"\n"
        f"{macros}\n"
        f"#endif // HW_ADC_CHANNELS_CUBEMX_H\n"
    )
    ADC_OUT.write_text(content, encoding="utf-8")
    total_inputs = sum(len(a.inputs) for a in adcs)
    print(f"  wrote {ADC_OUT.relative_to(REPO_ROOT)} "
          f"({len(adcs)} ADCs, {total_inputs} inputs)")


