# Driver
# ---------------------------------------------------------------------------

def main() -> int:
    if not CUBEMX_MAIN.is_file():
        print(f"Error: {CUBEMX_MAIN} not found.", file=sys.stderr)
        return 1
    source = CUBEMX_MAIN.read_text(encoding="utf-8", errors="replace")

    # GPIO ------------------------------------------------------------
    gpio_body = extract_function_body(source, "MX_GPIO_Init")
    if gpio_body is None:
        print("  WARN: MX_GPIO_Init not found in cubemx main.c; "
              "skipping GPIO header.", file=sys.stderr)
    else:
        pins_by_port = parse_mx_gpio_init(gpio_body)
        if not pins_by_port:
            print("  WARN: no HAL_GPIO_Init calls parsed; "
                  "writing empty GPIO header.", file=sys.stderr)
        write_gpio_header(pins_by_port)

    # ADC -------------------------------------------------------------
    # Find every MX_ADCN_Init function (typically MX_ADC1_Init,
    # MX_ADC2_Init, ...) and parse each. Both the prototype and the
    # definition match `void NAME(void)`, so dedupe by name.
    adc_funcs_raw = re.findall(
        r'\bvoid\s+(MX_ADC(\d+)_Init)\s*\(\s*void\s*\)', source)
    adc_funcs = sorted(set(adc_funcs_raw), key=lambda x: int(x[1]))
    adcs: list[ADCConfig] = []
    for func_name, n in adc_funcs:
        body = extract_function_body(source, func_name)
        if body is None:
            continue
        cfg = parse_mx_adc_init(body, hadc_var=f"hadc{n}")
        if cfg is None:
            print(f"  WARN: couldn't parse {func_name}; skipping.",
                  file=sys.stderr)
            continue
        adcs.append(cfg)
    if not adcs:
        print("  WARN: no MX_ADC*_Init functions found; "
              "writing empty ADC header.", file=sys.stderr)
    write_adc_header(adcs)

    # SPI -------------------------------------------------------------
    # Find every MX_SPIN_Init function and parse its hspiN.Init.* block.
    spi_funcs_raw = re.findall(
        r'\bvoid\s+(MX_SPI(\d+)_Init)\s*\(\s*void\s*\)', source)
    spi_funcs = sorted(set(spi_funcs_raw), key=lambda x: int(x[1]))
    spis: list[SPIConfig] = []
    for func_name, n in spi_funcs:
        body = extract_function_body(source, func_name)
        if body is None:
            continue
        cfg = parse_mx_spi_init(body, hspi_var=f"hspi{n}")
        if cfg is None:
            print(f"  WARN: couldn't parse {func_name}; skipping.",
                  file=sys.stderr)
            continue
        spis.append(cfg)
    if not spis:
        print("  WARN: no MX_SPI*_Init functions found; "
              "writing empty SPI header.", file=sys.stderr)
    write_spi_header(spis)

    # TIM -------------------------------------------------------------
    # Complementary (CHxN) outputs are detectable only from the GPIO AF
    # routing in HAL_TIM_MspPostInit (in hal_msp.c), not from MX_TIM*_Init.
    msp_source = ""
    if CUBEMX_MSP.is_file():
        msp_source = CUBEMX_MSP.read_text(encoding="utf-8", errors="replace")
    else:
        print(f"  WARN: {CUBEMX_MSP.name} not found; complementary outputs "
              "will all read false.", file=sys.stderr)
    complementary = parse_complementary_channels(msp_source)

    tim_funcs_raw = re.findall(
        r'\bvoid\s+(MX_TIM(\d+)_Init)\s*\(\s*void\s*\)', source)
    tim_funcs = sorted(set(tim_funcs_raw), key=lambda x: int(x[1]))
    tims: list[TIMConfig] = []
    for func_name, n in tim_funcs:
        body = extract_function_body(source, func_name)
        if body is None:
            continue
        cfg = parse_mx_tim_init(body, htim_var=f"htim{n}")
        if cfg is None:
            print(f"  WARN: couldn't parse {func_name}; skipping.",
                  file=sys.stderr)
            continue
        tims.append(cfg)
    if not tims:
        print("  WARN: no MX_TIM*_Init functions found; "
              "writing empty TIM header.", file=sys.stderr)
    write_tim_header(tims, complementary)

    return 0


if __name__ == "__main__":
    sys.exit(main())
