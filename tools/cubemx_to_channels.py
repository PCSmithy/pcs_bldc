@dataclass
class GPIOPinConfig:
    pin: str            # e.g. "GPIO_PIN_6" or "GPIO_PIN_15|GPIO_PIN_4"
    mode: str
    pull: str
    speed: str | None
    alternate: str | None


def parse_mx_gpio_init(body: str) -> dict[str, list[GPIOPinConfig]]:
    """Returns: {port_letter: [GPIOPinConfig, ...]}."""
    pins_by_port: dict[str, list[GPIOPinConfig]] = {}
    init_pattern = re.compile(
        r'HAL_GPIO_Init\s*\(\s*GPIO([A-G])\s*,\s*&GPIO_InitStruct\s*\)\s*;'
    )
    prev_end = 0
    for m in init_pattern.finditer(body):
        block = body[prev_end:m.start()]
        fields: dict[str, str] = {}
        for am in re.finditer(r'GPIO_InitStruct\.(\w+)\s*=\s*([^;]+);', block):
            fields[am.group(1)] = am.group(2).strip()
        if "Pin" not in fields:
            # No new Pin set this iteration -- shouldn't happen in well-formed
            # CubeMX output; skip rather than emit a corrupt entry.
            prev_end = m.end()
            continue
        port = m.group(1)
        pins_by_port.setdefault(port, []).append(GPIOPinConfig(
            pin=fields["Pin"],
            mode=fields.get("Mode", ""),
            pull=fields.get("Pull", ""),
            speed=fields.get("Speed"),
            alternate=fields.get("Alternate"),
        ))
        prev_end = m.end()
    return pins_by_port


def normalize_pin_expr(expr: str) -> str:
    """Wrap or-ed pin expressions in parens for safety inside struct context."""
    if "|" in expr or "+" in expr:
        return f"({expr})"
    return expr


def pin_name_str(port: str, pin_expr: str) -> str:
    """`GPIO_PIN_15|GPIO_PIN_4` on port C -> `PC15+PC4`."""
    nums = re.findall(r'GPIO_PIN_(\d+)', pin_expr)
    return "+".join(f"P{port}{n}" for n in nums)


def pin_mask_hex(pin_expr: str) -> str:
    """`GPIO_PIN_15|GPIO_PIN_4` -> `0x8010U` (OR of each line's bit)."""
    nums = re.findall(r'GPIO_PIN_(\d+)', pin_expr)
    mask = 0
    for n in nums:
        mask |= (1 << int(n))
    return f"0x{mask:04X}U"


def sim_mode_enum(hal_mode: str) -> str:
    """Map a HAL GPIO_MODE_* constant to the target-independent
    HW_GPIO_MODE_* enum used by the SIM config."""
    if hal_mode.startswith("GPIO_MODE_IT_"):
        return "HW_GPIO_MODE_INTERRUPT"
    if hal_mode in ("GPIO_MODE_OUTPUT_PP", "GPIO_MODE_OUTPUT_OD"):
        return "HW_GPIO_MODE_OUTPUT"
    # GPIO_MODE_INPUT (and anything else) maps to input.
    return "HW_GPIO_MODE_INPUT"


def gen_gpio_macros(pins_by_port: dict[str, list[GPIOPinConfig]]) -> str:
    parts: list[str] = []
    for port in sorted(pins_by_port):
        pins = pins_by_port[port]

        # --- stm32g4: real GPIO_InitTypeDef entries ---
        body: list[str] = []
        for p in pins:
            entries = [
                ("Pin", normalize_pin_expr(p.pin)),
                ("Mode", p.mode),
                ("Pull", p.pull),
            ]
            if p.speed is not None:
                entries.append(("Speed", p.speed))
            if p.alternate is not None:
                entries.append(("Alternate", p.alternate))
            body.append("    {")
            body.extend(aligned_assignments(entries, indent="        "))
            body.append("    },")
        parts.append(emit_macro(f"HW_GPIO_CUBEMX_PINS_PORT_{port}", body))
        parts.append("")

        # --- sim mirror: pin mask, mode enum, and human-readable name ---
        sim_entries: list[tuple[str, str, str]] = []
        for p in pins:
            sim_entries.append((
                pin_mask_hex(p.pin),
                sim_mode_enum(p.mode),
                pin_name_str(port, p.pin),
            ))
        # Align the mode column so the trailing name strings line up.
        mode_width = max((len(m) for _, m, _ in sim_entries), default=0)
        sim_body: list[str] = []
        for mask, mode, name in sim_entries:
            sim_body.append(
                f'    {{ .pin = {mask}, .mode = {(mode + ",").ljust(mode_width + 1)} '
                f'.pinNameStr = "{name}" }},'
            )
        parts.append(emit_macro(
            f"HW_GPIO_CUBEMX_SIM_PINS_PORT_{port}", sim_body))
        parts.append("")

    return "\n".join(parts).rstrip() + "\n"


def write_gpio_header(pins_by_port: dict[str, list[GPIOPinConfig]]) -> None:
    macros = gen_gpio_macros(pins_by_port)
    content = (
        f"{file_header('cubemx_to_channels.py')}"
        f"\n"
        f"#ifndef HW_GPIO_CHANNELS_CUBEMX_H\n"
        f"#define HW_GPIO_CHANNELS_CUBEMX_H\n"
        f"\n"
        f"{macros}\n"
        f"#endif // HW_GPIO_CHANNELS_CUBEMX_H\n"
    )
    GPIO_OUT.write_text(content, encoding="utf-8")
    print(f"  wrote {GPIO_OUT.relative_to(REPO_ROOT)} "
          f"({sum(len(v) for v in pins_by_port.values())} pins, "
          f"{len(pins_by_port)} ports)")


