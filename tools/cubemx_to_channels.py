#!/usr/bin/env python3
"""Generate `HW_<Module>_channels.cubemx.h` files from CubeMX-generated
main.c, holding macros for the CubeMX-derived field values that the
hand-written `HW_<Module>_channels.c` references.

Reads:  sw/fw/stm32cube/g4/Core/Src/main.c
Writes: sw/fw/src/hw/GPIO/HW_GPIO_channels.cubemx.h
        sw/fw/src/hw/ADC/HW_ADC_channels.cubemx.h

Each generated header defines macros like:
    HW_GPIO_CUBEMX_PINS_PORT_C       # used inside `static const GPIO_InitTypeDef[] = { ... }`
    HW_ADC_CUBEMX_HADC_INIT_ADC1     # used inside `.hadc = { .Init = { ... } }`
    HW_ADC_CUBEMX_INPUTS_ADC1        # used inside `.inputs = { ... }`
    ...

Sim mirrors are emitted alongside the stm32g4 macros so the SIM branch
of channels.c can use them without divergent maintenance.

Called from tools/convert_cubemx_to_canonical.sh. Stdlib only.
"""

import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CUBEMX_MAIN = REPO_ROOT / "sw/fw/stm32cube/g4/Core/Src/main.c"
CUBEMX_MSP = REPO_ROOT / "sw/fw/stm32cube/g4/Core/Src/stm32g4xx_hal_msp.c"
GPIO_OUT = REPO_ROOT / "sw/fw/src/hw/GPIO/HW_GPIO_channels.cubemx.h"
ADC_OUT = REPO_ROOT / "sw/fw/src/hw/ADC/HW_ADC_channels.cubemx.h"
SPI_OUT = REPO_ROOT / "sw/fw/src/hw/SPI/HW_SPI_channels.cubemx.h"
TIM_OUT = REPO_ROOT / "sw/fw/src/hw/TIM/HW_TIM_channels.cubemx.h"

# STM32G4 timers with a 32-bit counter; the rest are 16-bit. Used to fill
# the SIM config's counterWidthBits (the stm32g4 side never needs it).
TIM_32BIT_INSTANCES = {2, 5}

# Timer kernel clock the SIM config's countsPerUs is derived against: HSE
# 24 MHz (HSE_VALUE in sw/fw/src/hw/stm32g4/stm32g4xx_hal_conf.h) / PLLM 2
# x PLLN 24 / PLLR 2 = 144 MHz, with both APB prescalers at 1 so the timer
# clock equals HCLK. Update alongside SystemClock_Config.
TIM_KERNEL_CLOCK_HZ = 144_000_000

# countsPerUs values that do not follow from the prescaler. A timer whose
# prescaled rate is not a whole number of counts per microsecond needs one
# here -- a deliberate choice by the owner of the sim timebase, recorded
# rather than silently rounded.
TIM_COUNTS_PER_US_OVERRIDE: dict[int, int] = {}


# ---------------------------------------------------------------------------
# Common helpers
# ---------------------------------------------------------------------------

def extract_function_body(source: str, name: str) -> str | None:
    """Return the `{...}` body of `[static] void <name>(void) { ... }`."""
    pattern = re.compile(
        rf'\b(?:static\s+)?void\s+{re.escape(name)}\s*\(\s*void\s*\)\s*\{{'
    )
    m = pattern.search(source)
    if not m:
        return None
    start = m.end()
    depth = 1
    i = start
    while i < len(source):
        c = source[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return source[start:i]
        i += 1
    return None


def emit_macro(name: str, body_lines: list[str]) -> str:
    """Format a multi-line `#define` from body lines (without trailing `\\`)."""
    if not body_lines:
        return f"#define {name}"
    out = [f"#define {name} \\"]
    for i, line in enumerate(body_lines):
        suffix = " \\" if i < len(body_lines) - 1 else ""
        out.append(line + suffix)
    return "\n".join(out)


def aligned_assignments(items: list[tuple[str, str]], indent: str) -> list[str]:
    """Format `(field, value)` pairs as `.field = value,` lines, with `=`
    aligned to the same column for readability. Matches the project's
    hand-written struct-init style."""
    if not items:
        return []
    width = max(len(f) for f, _ in items)
    return [f"{indent}.{f.ljust(width)} = {v}," for f, v in items]


def file_header(generator_call: str) -> str:
    return (
        f"// AUTO-GENERATED by tools/{generator_call} from\n"
        f"// sw/fw/stm32cube/g4/Core/Src/main.c. Do not hand-edit.\n"
        f"//\n"
        f"// Re-generate via: tools/convert_cubemx_to_canonical.sh\n"
        f"//\n"
        f"// This file holds macros containing CubeMX-derived field values.\n"
        f"// The hand-written HW_*_channels.c references them inside its\n"
        f"// struct initializers; user-managed fields (triggerMode, vref,\n"
        f"// injectedInputs, ...) live there too, outside the macro\n"
        f"// expansions.\n"
    )


